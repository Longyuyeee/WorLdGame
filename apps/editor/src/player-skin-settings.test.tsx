import { fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { expect, it, vi } from "vitest";
import { createProjectTemplate } from "@world-studio/project-domain";
import { SettingsWorkspace } from "./SettingsWorkspace";
vi.mock("./player-skin-preview", () => ({ PlayerSkinPreview: () => <aside>静音预览</aside> }));
const fresh = () => createProjectTemplate("Appearance", "018f08d8-71a1-7bc2-a627-2f4a843ee156");
it("edits another page, copies shared window style, undoes it and applies ending copy without changing other page widths", async () => {
  const change = vi.fn();
  render(<SettingsWorkspace project={fresh()} saveStatus="saved" onProjectChange={change} onSave={() => {}} onClose={() => {}} />);
  fireEvent.click(within(screen.getByRole("navigation", { name: "游戏界面分区" })).getByRole("button", { name: /其他页面/u }));
  fireEvent.click(screen.getByRole("button", { name: "宽阔面板" }));
  fireEvent.change(screen.getByLabelText("本页圆角"), { target: { value: "9" } });
  fireEvent.change(screen.getByLabelText("宽屏存档列数"), { target: { value: "3" } });
  fireEvent.click(screen.getByRole("button", { name: "统一窗体风格" }));
  fireEvent.click(screen.getByRole("button", { name: "撤销外观调整" }));
  fireEvent.change(screen.getByLabelText("正在编辑的界面"), { target: { value: "ending" } });
  expect(screen.getByLabelText("本页宽度")).toHaveValue("600");
  expect(screen.getByLabelText("本页圆角")).toHaveValue("20");
  fireEvent.change(screen.getByLabelText("返回按钮文字"), { target: { value: "合上回信" } });
  fireEvent.click(screen.getByRole("button", { name: "应用玩家外观" }));
  await waitFor(() => expect(change).toHaveBeenCalledOnce());
  expect(change.mock.lastCall?.[0].ui.preservedFields.webPlayerAppearance.skin.screens).toMatchObject({ saveColumns: 3, panels: { save: { width: 1040, radius: 9 }, ending: { width: 600, radius: 20 } }, ending: { returnLabel: "合上回信" } });
});
it("previews drafts, undoes a preset and applies title plus reading styles together", async () => {
  const change = vi.fn();
  render(<SettingsWorkspace project={fresh()} saveStatus="saved" onProjectChange={change} onSave={() => {}} onClose={() => {}} />);
  fireEvent.change(screen.getByLabelText("开始按钮文字"), { target: { value: "打开回信" } });
  const nav = screen.getByRole("navigation", { name: "游戏界面分区" });
  fireEvent.click(within(nav).getByRole("button", { name: /皮肤与动效/u }));
  fireEvent.click(screen.getByRole("button", { name: "海风书签" }));
  fireEvent.click(screen.getByRole("button", { name: "撤销外观调整" }));
  fireEvent.change(screen.getByLabelText("窗体颜色值"), { target: { value: "#182f36" } });
  fireEvent.click(within(nav).getByRole("button", { name: /阅读与选项/u }));
  fireEvent.change(screen.getByLabelText("对白框圆角"), { target: { value: "7" } });
  expect(change).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("button", { name: "应用玩家外观" }));
  await waitFor(() => expect(change).toHaveBeenCalledOnce());
  expect(change.mock.lastCall?.[0].ui.preservedFields.webPlayerAppearance.skin).toMatchObject({ title: { startLabel: "打开回信" }, reading: { radius: 7 }, colors: { panel: "#182f36" } });
});
it("keeps a title draft while newly imported fonts become selectable", async () => {
  const project = fresh(), change = vi.fn(), props = { saveStatus: "saved" as const, onProjectChange: change, onSave: () => {}, onClose: () => {} };
  const { rerender } = render(<SettingsWorkspace {...props} project={project} />);
  fireEvent.change(screen.getByLabelText("开始按钮文字"), { target: { value: "打开信封" } });
  rerender(<SettingsWorkspace {...props} project={{ ...project, assets: { ...project.assets, assets: [{ assetId: "new_font", kind: "font", displayName: "自定义字体", source: { mimeType: "font/woff2", byteLength: 100 }, assetIndexMetadata: { inspection: { status: "pass" } } }] } }} />);
  fireEvent.click(within(screen.getByRole("navigation", { name: "游戏界面分区" })).getByRole("button", { name: /字体/u }));
  await within(screen.getByLabelText("正文字体")).findByRole("option", { name: "自定义字体" });
  fireEvent.change(screen.getByLabelText("正文字体"), { target: { value: "asset:new_font" } });
  fireEvent.click(screen.getByRole("button", { name: "应用玩家外观" }));
  await waitFor(() => expect(change.mock.lastCall?.[0].ui.preservedFields.webPlayerAppearance.skin).toMatchObject({ title: { startLabel: "打开信封" }, fonts: { body: "asset:new_font" } }));
});
