import { describe, expect, it, vi } from "vitest";
import { loadProject, saveProject, migrateS0Project, type S0Project } from "@world-studio/project-domain";
import { applyWebPublication, readWebPublication } from "./web-publication";
import { createBlobDigest } from "@world-studio/project-persistence";
import branching from "../../../fixtures/projects/branching/project.s0.json";
import media from "../../../fixtures/projects/media/media-golden.json";
import { createFormalWebArtifact, createFormalWebDirectoryArtifact } from "./formal-web-export";
import { unzipSync } from "fflate";

describe("formal Web game packaging", () => {
  it("reads shared source blobs once per build but checks fresh storage on the next build", async () => {
    const source=loadProject(migrateS0Project(branching as S0Project).files);
    const image=media.assets.find(a=>a.assetId==="media_sunset")!;
    const bytes=Uint8Array.from(atob(image.base64),c=>c.charCodeAt(0)), digest=createBlobDigest(bytes);
    const project={...source,assets:{...source.assets,assets:["copy-a","copy-b"].map(assetId=>({assetId,kind:"cg",source:{digest,byteLength:bytes.length,mimeType:image.mimeType}}))}};
    const read=vi.fn(async():Promise<Uint8Array|null>=>bytes),runtime={javascript:"",css:""};
    await createFormalWebArtifact(project,{read},runtime);expect(read).toHaveBeenCalledTimes(1);
    read.mockResolvedValue(null);
    await expect(createFormalWebArtifact(project,{read},runtime)).rejects.toThrow("缺失或不完整");
    read.mockResolvedValue(new Uint8Array(bytes.length));
    await expect(createFormalWebArtifact(project,{read},runtime)).rejects.toThrow("缺失或不完整");
    read.mockResolvedValue(bytes);
    await createFormalWebDirectoryArtifact(project,{read},runtime);expect(read).toHaveBeenCalledTimes(4);
  });
  it("cancels before packaging and permits a fresh build without mutating the project", async () => {
    const project = loadProject(migrateS0Project(branching as S0Project).files);
    const controller = new AbortController(); controller.abort();
    const reader = { read: async () => { throw Error("Cancelled build must not read assets"); } };
    const bundle = { javascript: "", css: "" };
    await expect(createFormalWebArtifact(project, reader, bundle, controller.signal)).rejects.toMatchObject({ name: "AbortError" });
    await expect(createFormalWebDirectoryArtifact(project, reader, bundle, controller.signal)).rejects.toMatchObject({ name: "AbortError" });
    expect((await createFormalWebArtifact(project, { read: async () => null }, bundle)).html).toContain("world-project");
  });
  it("persists publication settings and exports the player-facing title/version without renaming the source project", async () => {
    const source = loadProject(migrateS0Project(branching as S0Project).files);
    const settings = { name: "发布作品", version: "2.1.0-beta", iconAssetId: "" };
    const project = loadProject(saveProject(applyWebPublication(source, settings)));
    expect(project.manifest.title).toBe(source.manifest.title);
    expect(readWebPublication(project)).toEqual(settings);
    const single = await createFormalWebArtifact(project, { read: async () => null }, { javascript: "", css: "" });
    const singlePage = new DOMParser().parseFromString(single.html, "text/html");
    expect(singlePage.getElementById('world-publication-home')?.hidden).toBe(true);
    expect(singlePage.getElementById('world-publication-version')?.textContent).toBe('发布作品 · 2.1.0-beta');
    expect(single.html).not.toContain('--player-viewport-offset:');
    const artifact = await createFormalWebDirectoryArtifact(project, { read: async () => null }, { javascript: "", css: "" });
    const files = unzipSync(artifact.archive);
    const text = (path: string) => new TextDecoder().decode(files[path]);
    expect(JSON.parse(text("manifest.webmanifest")).name).toBe(settings.name);
    expect(JSON.parse(text("build-info.json")).publication).toEqual(settings);
    expect(text("index.html")).toContain('content="2.1.0-beta"');
    expect(text("index.html")).toContain('<title>发布作品</title>');
    expect(artifact.filename).toBe("发布作品-web.zip");
    expect(() => applyWebPublication(project, { ...settings, version: "<bad>" })).toThrow("版本");
    expect(() => applyWebPublication(project, { ...settings, iconAssetId: "missing" })).toThrow("图标素材");
  });
  it("packages the exact Canonical and original media bytes without external URLs", async () => {
    const project = loadProject(migrateS0Project(branching as S0Project).files);
    const image = media.assets.find((asset) => asset.assetId === "media_sunset")!;
    const bytes = Uint8Array.from(atob(image.base64), (value) => value.charCodeAt(0));
    const digest = createBlobDigest(bytes);
    const exported = { ...project, manifest: { ...project.manifest, title: "My game </script>" }, assets: { ...project.assets, assets: [{ assetId: image.assetId, kind: "cg", source: { digest, byteLength: bytes.length, mimeType: image.mimeType } }] } };
    const artifact = await createFormalWebArtifact(exported, { read: async () => bytes }, { javascript: "window.started=true;", css: "body{margin:0}" });
    const page = new DOMParser().parseFromString(artifact.html, "text/html");
    const payload = JSON.parse(page.getElementById("world-project")!.textContent!);
    expect(payload.project).toEqual(exported);
    expect(payload.mediaAssets[0].url).toBe(`data:${image.mimeType};base64,${image.base64}`);
    expect(page.querySelectorAll("script[src],link[href]")).toHaveLength(0);
    expect(page.title).toBe(exported.manifest.title);
    await expect(createFormalWebArtifact(exported, { read: async () => null }, { javascript: "", css: "" })).rejects.toThrow("重新导入后重试");
    await expect(createFormalWebArtifact(exported, { read: async () => new Uint8Array([1]) }, { javascript: "", css: "" })).rejects.toThrow("缺失或不完整");
    const badIcon = applyWebPublication(exported, { name: "作品", version: "1.0.0", iconAssetId: image.assetId });
    await expect(createFormalWebDirectoryArtifact(badIcon, { read: async () => bytes }, { javascript: "", css: "" })).rejects.toThrow("正方形 PNG");
    const directory = await createFormalWebDirectoryArtifact(exported, { read: async () => bytes }, { javascript: "window.started=true;", css: "body{margin:0}" });
    const files = unzipSync(directory.archive);
    const text = (path: string) => new TextDecoder().decode(files[path]);
    const directoryPage = new DOMParser().parseFromString(text("index.html"), "text/html");
    const directoryPayload = JSON.parse(directoryPage.getElementById("world-project")!.textContent!);
    expect(directory.filename).toBe("My-game-script--web.zip");
    expect(directoryPayload.project).toEqual(exported);
    expect(files[directoryPayload.mediaAssets[0].url]).toEqual(bytes);
    expect(directoryPage.querySelector("script[src]")?.getAttribute("src")).toBe("player.js");
    expect(text("player.js")).toBe("window.started=true;");
    expect(text("使用说明.txt")).toContain("完整解压");
    expect(text("使用说明.txt")).toContain("Node.js 22");
    expect(text("start-preview.cmd")).toContain('node "%~dp0preview.mjs" %*');
    expect(text("preview.mjs")).toContain("127.0.0.1");
    expect(text('deployment-check.mjs')).toContain('prepareWebsiteDirectory');
    expect(text('check-deployment.cmd')).toContain('--interactive');
    expect(text('preview.mjs')).toContain('inspectLocalSite');
    const info = JSON.parse(text("build-info.json"));
    expect(info.projectDigest).toBe(artifact.projectDigest);
    for (const file of info.files) expect(createBlobDigest(files[file.path]!)).toBe(file.digest);
    expect(directoryPage.querySelector('link[rel="manifest"]')?.getAttribute("href")).toBe("manifest.webmanifest");
    expect(directoryPage.getElementById("offline-action")?.textContent).toBe("下载离线内容");
    const manifest = JSON.parse(text("manifest.webmanifest"));
    expect(manifest.start_url).toBe("./index.html");
    expect(manifest.scope).toBe("./");
    const inventory = JSON.parse(text("sw.js").match(/^const inventory = (.*);$/m)![1]!);
    expect(inventory["preview.mjs"]).toBeUndefined();
    expect(inventory["start-preview.cmd"]).toBeUndefined();
    expect(inventory['deployment-check.mjs']).toBeUndefined();
    expect(inventory['check-deployment.cmd']).toBeUndefined();
    expect(info.files.some((row: { path: string }) => row.path === 'deployment-check.mjs')).toBe(false);
    for (const [path, digest] of Object.entries(inventory)) expect(createBlobDigest(files[path]!)).toBe(digest);
    expect(() => new Function(text("sw.js"))).not.toThrow();
    expect(() => new Function(text("offline.js"))).not.toThrow();
    const updated = unzipSync((await createFormalWebDirectoryArtifact(exported, { read: async () => bytes }, { javascript: "window.started='v2';", css: "body{margin:0}" })).archive);
    expect(new TextDecoder().decode(updated["sw.js"])).not.toBe(text("sw.js"));
    await expect(createFormalWebDirectoryArtifact(exported, { read: async () => null }, { javascript: "", css: "" })).rejects.toThrow("重新导入后重试");
  });
});
