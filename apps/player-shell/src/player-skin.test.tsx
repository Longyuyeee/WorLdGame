import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { expect, it, vi } from "vitest";
import { applyWebPlayerAppearance, createProjectTemplate, DEFAULT_WEB_PLAYER_APPEARANCE, webPlayerSkinPreset } from "@world-studio/project-domain";
import { PlayerShell } from "./PlayerShell";
const fresh = () => createProjectTemplate("回信", "018f08d8-71a1-7bc2-a627-2f4a843ee155");
it("loads distinct authored font roles, shares inherited roles and releases only its own faces", async () => {
  const previous = Object.getOwnPropertyDescriptor(document, "fonts"), fontSet = { add: vi.fn(), delete: vi.fn() };
  Object.defineProperty(document, "fonts", { value: fontSet, configurable: true });
  const load = vi.fn(function(this: { family: string }) { return Promise.resolve(this); });
  vi.stubGlobal("FontFace", class { constructor(readonly family: string) {} load = load; });
  const base = fresh(), skin = webPlayerSkinPreset("letter");
  const assets = ["body_font", "title_font"].map(assetId => ({ assetId, kind: "font", displayName: assetId, source: { mimeType: "font/woff2", byteLength: 100 }, assetIndexMetadata: { inspection: { status: "pass" } } }));
  const project = applyWebPlayerAppearance({ ...base, assets: { ...base.assets, assets } }, { ...DEFAULT_WEB_PLAYER_APPEARANCE, skin: { ...skin, title: { ...skin.title, startLabel: "打开回信" }, fonts: { body: "asset:body_font", title: "asset:title_font", name: "inherit", ui: "sans" } } });
  const { container, unmount } = render(<PlayerShell project={project} mediaAssets={assets.map(asset => ({ assetId: asset.assetId, displayName: asset.displayName, mimeType: "font/woff2", url: `blob:${asset.assetId}` }))} />);
  await waitFor(() => expect(fontSet.add).toHaveBeenCalledTimes(2));
  expect(load).toHaveBeenCalledTimes(2);
  expect(container.querySelector("main")?.style.getPropertyValue("--player-font-family")).toContain("WorldProjectFont_body_font");
  expect(container.querySelector("main")?.style.getPropertyValue("--skin-font-title")).toContain("WorldProjectFont_title_font");
  expect(container.querySelector("main")).toHaveAttribute("data-player-skin", "1");
  expect(screen.getByRole("button", { name: /打开回信/u })).toBeVisible();
  unmount(); expect(fontSet.delete).toHaveBeenCalledTimes(2);
  vi.unstubAllGlobals();
  if (previous) Object.defineProperty(document, "fonts", previous); else Reflect.deleteProperty(document, "fonts");
});
it("renders authored reading geometry and honors the same high-contrast and reduce-motion controls", () => {
  const base = fresh(), scene = base.scenes[0]!, skin = webPlayerSkinPreset("ocean");
  const project = applyWebPlayerAppearance({ ...base, scripts: { [scene.id]: { ...base.scripts[scene.id]!, statements: [{ id: "line", kind: "narration", textId: "words", text: "写给明天的你" }, { id: "end", kind: "end", endingName: "完" }] } } }, { ...DEFAULT_WEB_PLAYER_APPEARANCE, skin: { ...skin, reading: { ...skin.reading, radius: 7, fontSize: 24 } } });
  const { container } = render(<PlayerShell project={project} editorPreview={{ autoStart: true }} />);
  expect(screen.getByRole("button", { name: "继续下一句" })).toHaveTextContent("写给明天的你");
  const shell = container.querySelector("main")!;
  expect(shell.style.getPropertyValue("--skin-window-radius")).toBe("7px");
  expect(shell).toHaveAttribute("data-skin-control-motion", "lift");
  fireEvent.click(screen.getByRole("button", { name: "打开阅读菜单" }));
  fireEvent.click(screen.getByRole("button", { name: "打开玩家设置" }));
  fireEvent.click(screen.getByLabelText("高对比阅读"));
  fireEvent.click(screen.getByLabelText("减少动效"));
  expect(shell).toHaveAttribute("data-settings-high-contrast", "true");
  expect(shell).toHaveAttribute("data-settings-reduce-motion", "true");
});
